#include "libft.h"

int	ft_tolower(int c)
{
	if (c >= 'A' && c <= 'Z')
		return (c + 32);
	return (c);
}

#ifdef FT_MAIN
int	main(void)
{
	printf("tolower: %c\n", ft_tolower('Z'));
	return (0);
}
#endif
