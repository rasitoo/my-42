#include "libft.h"
#include <unistd.h>

void	ft_putendl_fd(char *s, int fd)
{
	/* Simple idea: write a string followed by a newline. */
	if (s != NULL)
		write(fd, s, ft_strlen(s));
	write(fd, "\n", 1);
}

#ifdef FT_MAIN
int	main(void)
{
	ft_putendl_fd("hi", 1);
	return (0);
}
#endif
