#include "libft.h"

t_list	*ft_lstnew(void *content)
{
	t_list	*node;

	/* Simple idea: allocate and initialize a list node. */
	node = (t_list *)malloc(sizeof(t_list));
	if (node == NULL)
		return (NULL);
	node->content = content;
	node->next = NULL;
	return (node);
}

#ifdef FT_MAIN
int	main(void)
{
	t_list	*node;

	node = ft_lstnew("x");
	printf("lstnew: %s\n", (char *)node->content);
	free(node);
	return (0);
}
#endif
