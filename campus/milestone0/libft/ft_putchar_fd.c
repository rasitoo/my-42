#include "libft.h"
#include <unistd.h>

void	ft_putchar_fd(char c, int fd)
{
	/* Simple idea: write one character to a file descriptor. */
	write(fd, &c, 1);
}

#ifdef FT_MAIN
int	main(void)
{
	ft_putchar_fd('X', 1);
	return (0);
}
#endif
