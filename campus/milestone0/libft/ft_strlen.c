#include "libft.h"

size_t	ft_strlen(const char *s)
{
	size_t	idx;

	idx = 0;
	while (s[idx] != '\0')
		idx++;
	return (idx);
}

#ifdef FT_MAIN
int	main(void)
{
	printf("strlen: %zu\n", ft_strlen("abc"));
	return (0);
}
#endif
